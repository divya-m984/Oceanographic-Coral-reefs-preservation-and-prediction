"""
Regression tests for the P0 scientific-disclosure hardening.

Background
----------
The dataset audit of 2026-08-19 established that both project targets are
produced by *label-construction leakage / circular supervision*: the label
columns are algorithmically generated by weighted formulas over other columns in
the same file, and those generating columns are then supplied to the models as
predictors.  Reported metrics therefore measure recovery of the synthetic
generation rules and MLOps pipeline behaviour, not real-world ecological
validity.

These tests do not evaluate model quality and never train, register, or load a
model.  They assert only that the disclosure of that finding remains present
wherever metrics are surfaced, so it cannot be silently dropped by a later edit.

Nothing here mutates any canonical artifact.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent

AUDIT_REPORT = PROJECT_ROOT / "docs" / "audits" / "dataset_scientific_audit_2026-08-19.md"

# SHA-256 of the synthetic prototype dataset the 2026-08-19 audit examined.
AUDITED_DATASET_SHA256 = "a03cb3e92ba1904ae07147da95f96aa689d092d56fc41b040b701a101ad8f458"


def _read(relative: str) -> str:
    """
    Return the text of a repository file, normalised for tolerant phrase matching.

    Disclosure wording legitimately spans Python implicit string concatenation
    and carries Markdown emphasis, so a phrase such as "not validated real-world"
    may appear in the source as ``not validated "\\n    "real-world`` or as
    ``**not** real-world``.  Stripping quotes and emphasis markers and collapsing
    whitespace lets these tests assert on meaning rather than on line wrapping.
    """
    text = (PROJECT_ROOT / relative).read_text(encoding="utf-8").lower()
    for ch in ('"', "'", "*", "`", "\\"):
        text = text.replace(ch, "")
    return " ".join(text.split())


# ---------------------------------------------------------------------------
# The preserved audit
# ---------------------------------------------------------------------------


class TestAuditPreserved:
    """The dataset audit must remain in version control, dated and identifiable."""

    def test_audit_report_exists(self) -> None:
        assert AUDIT_REPORT.is_file(), f"audit report missing at {AUDIT_REPORT}"

    def test_audit_report_is_dated(self) -> None:
        text = AUDIT_REPORT.read_text(encoding="utf-8")
        assert "2026-08-19" in text
        assert "dataset_scientific_audit_2026-08-19" in AUDIT_REPORT.name + ".md"

    def test_audit_identifies_canonical_dataset_hash(self) -> None:
        """The audit must state which exact dataset its conclusions apply to."""
        text = AUDIT_REPORT.read_text(encoding="utf-8")
        assert AUDITED_DATASET_SHA256 in text

    def test_audit_records_closed_form_diagnostic(self) -> None:
        """The closed-form vs learned comparison is the evidence for circularity."""
        text = AUDIT_REPORT.read_text(encoding="utf-8").lower()
        for value in ("0.770", "0.812", "0.760", "0.791"):
            assert value in text, f"closed-form diagnostic value {value} missing"

    def test_audit_separates_diagnostic_from_registered_metrics(self) -> None:
        """
        The closed-form numbers are an audit diagnostic.  The report must say so,
        so they are never mistaken for registered champion metrics.
        """
        text = AUDIT_REPORT.read_text(encoding="utf-8").lower()
        assert "audit diagnostic" in text
        # The canonical champion figures must still be named as the authoritative ones.
        assert "0.7871" in text and "0.8029" in text


