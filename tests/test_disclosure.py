# (repo-relative path, human label) for every surface that presents metrics or
# predictions to a user or developer.
DISCLOSURE_SURFACES = [
    ("README.md", "README"),
    ("docs/architecture.md", "architecture doc"),
    ("docs/course_evidence.md", "course evidence doc"),
    ("docs/data_dictionary.md", "data dictionary"),
    ("src/dashboard/views/6_Model_Performance.py", "dashboard model-performance page"),
    ("src/dashboard/views/9_Governance.py", "dashboard governance page"),
    ("src/api/schemas.py", "API schemas"),
    ("src/api/main.py", "API app"),
    ("src/models/model_card.py", "model card generator"),
]


@pytest.mark.parametrize(("path", "label"), DISCLOSURE_SURFACES)
def test_surface_names_the_leakage_mechanism(path: str, label: str) -> None:
    """
    Every metric-bearing surface must name the actual problem, not just say
    "synthetic".  The audit's finding is label-construction leakage / circular
    supervision, and the wording must reflect that.
    """
    text = _read(path)
    assert "label-construction leakage" in text or "circular supervision" in text, (
        f"{label} ({path}) does not disclose label-construction leakage / circular supervision"
    )


@pytest.mark.parametrize(("path", "label"), DISCLOSURE_SURFACES)
def test_surface_states_labels_are_algorithmically_generated(path: str, label: str) -> None:
    """The disclosure must say the labels are generated, not observed."""
    text = _read(path)
    assert "algorithmically generated" in text, (
        f"{label} ({path}) does not state that labels are algorithmically generated"
    )


@pytest.mark.parametrize(("path", "label"), DISCLOSURE_SURFACES)
def test_surface_does_not_claim_real_world_validity(path: str, label: str) -> None:
    """
    The disclosure must explicitly deny real-world predictive validity rather
    than leaving the reader to infer it.
    """
    text = _read(path)
    denials = (
        "not validated real-world",
        "not real-world",
        "not real-world ecological validity",
        "not real-world coral",
        "do not indicate real-world",
        "not evidence of ecological validity",
        "not real-world ecological",
    )
    assert any(d in text for d in denials), (
        f"{label} ({path}) does not explicitly deny real-world predictive validity"
    )


