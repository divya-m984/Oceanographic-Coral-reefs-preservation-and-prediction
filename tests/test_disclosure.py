class TestAuditInboxIgnored:
    """
    data/audit_inbox/ holds third-party literature and externally licensed
    material (IUCN Red List spatial data prohibits redistribution).  It must
    never be committable.
    """

    def test_gitignore_has_rule(self) -> None:
        assert "data/audit_inbox/" in (PROJECT_ROOT / ".gitignore").read_text(encoding="utf-8")

    def test_git_actually_ignores_the_directory(self) -> None:
        result = subprocess.run(
            ["git", "check-ignore", "-q", "data/audit_inbox/"],
            cwd=PROJECT_ROOT,
            capture_output=True,
            check=False,
        )
        assert result.returncode == 0, "git does not ignore data/audit_inbox/"

    def test_no_iucn_redlist_archive_in_repository(self) -> None:
        """The IUCN dataset must never be copied into version control."""
        matches = list(PROJECT_ROOT.rglob("redlist_species_data_*"))
        assert not matches, f"IUCN Red List data found in repository: {matches}"
