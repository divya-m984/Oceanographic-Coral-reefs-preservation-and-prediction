def _make_task_bundle(task_dir: Path, label_names: list[str], task: str) -> dict:
    """
    Write a minimal valid bundle for *task* to *task_dir*.

    Returns the metadata dict that was written.
    """
    task_dir.mkdir(parents=True, exist_ok=True)

    # Build a tiny training set with the right feature columns
    rng = np.random.default_rng(42)
    n = len(label_names) * 10
    X_train = pd.DataFrame(rng.standard_normal((n, len(_FEATURE_COLS))), columns=_FEATURE_COLS)
    y_train = np.tile(label_names, n // len(label_names) + 1)[:n]

    # Preprocessor: a fitted sklearn Pipeline with StandardScaler
    preprocessor = Pipeline([("scaler", StandardScaler())])
    preprocessor.fit(X_train)

    # Payload: label encoder + estimator
    le = LabelEncoder()
    le.fit(label_names)
    y_encoded = le.transform(y_train)

    clf = LogisticRegression(max_iter=200, random_state=0)
    clf.fit(preprocessor.transform(X_train), y_encoded)

    payload = {"estimator": clf, "label_encoder": le}

    # Write joblib files
    preprocessor_path = task_dir / "preprocessor.joblib"
    payload_path = task_dir / "payload.joblib"
    joblib.dump(preprocessor, preprocessor_path)
    joblib.dump(payload, payload_path)

    checksum_payload = _sha256_file(payload_path)
    checksum_preprocessor = _sha256_file(preprocessor_path)

    registered_model_names = {
        "health": "coralsense_reef_health",
        "restoration": "coralsense_restoration_suitability",
    }

    metadata = {
        "task": task,
        "registered_model_name": registered_model_names[task],
        "version": 1,
        "alias": "champion",
        "run_id": "abc123def456abc1",
        "algo_name": "LogisticRegression",
        "label_names": label_names,
        "cv_macro_f1": 0.75,
        "checksum_payload": checksum_payload,
        "checksum_preprocessor": checksum_preprocessor,
        "exported_at": "2026-01-01T00:00:00+00:00",
        "coralsense_version": "0.1.0",
        "synthetic_data_disclaimer": "Synthetic data only.",
    }

    with (task_dir / "metadata.json").open("w") as fh:
        json.dump(metadata, fh)

    return metadata


