# Entry point for direct execution
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    import uvicorn

    uvicorn.run(
        "src.api.main:app",
        host=_HOST,
        port=_PORT,
        log_level=_LOG_LEVEL,
        reload=False,
    )
