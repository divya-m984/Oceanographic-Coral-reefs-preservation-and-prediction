"""
src/api/main.py — FastAPI inference service for CoralSense MLOps.

Launch
------
    uvicorn src.api.main:app --host 127.0.0.1 --port 8000

Endpoints
---------
    GET  /                      — Project index and documentation links.
    GET  /health                — Process liveness (always 200 while serving).
    GET  /ready                 — Deployment readiness (503 unless both models load).
    GET  /model-info            — Champion model metadata (safe fields only).
    POST /predict/reef-health   — Single reef-health prediction.
    POST /predict/restoration   — Single restoration-suitability prediction.
    POST /predict/both          — Both predictions for one observation.
    POST /predict/batch         — Batch predictions (max 50 observations).

Security notes
--------------
- No internal paths, SQL details, or tracebacks are returned to clients.
- No model registration or promotion occurs at runtime.
- No retraining; preprocessors are used in transform-only mode.
- Wildcard credentialed CORS is never enabled.

SYNTHETIC-DATA DISCLAIMER
--------------------------
All predictions are generated by a model trained on a *synthetic prototype
dataset* whose labels are *algorithmically generated* from variables that are
themselves supplied to the models as predictors (label-construction leakage /
circular supervision).  Reported metrics measure recovery of the synthetic
generation rules and MLOps pipeline behaviour, not validated real-world
coral-reef prediction accuracy.  There is no independent biological ground
truth in this project and no external validation has been performed.

Predictions must NOT be used to guide real-world coral-reef conservation
decisions.  See docs/audits/dataset_scientific_audit_2026-08-19.md.
"""

from __future__ import annotations

import logging
import os
from contextlib import asynccontextmanager
from datetime import UTC, datetime
from typing import Annotated, Any

import pandas as pd
from fastapi import Depends, FastAPI, HTTPException, Request, Response
from fastapi.middleware.cors import CORSMiddleware

from src.api.model_loader import ModelLoader
from src.api.schemas import (
    _DISCLAIMER,
    BatchPredictionResponse,
    BatchRequest,
    BothPredictionResponse,
    ModelInfoResponse,
    ObservationInput,
    PredictionResponse,
    ReadinessResponse,
    RootResponse,
    ServiceHealthResponse,
)

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Application settings from environment variables
# ---------------------------------------------------------------------------

_HOST: str = os.getenv("CORALSENSE_HOST", "127.0.0.1")
# Cloud hosts (Render, Cloud Run, Heroku) inject the listening port as PORT.
# Precedence: explicit CORALSENSE_PORT > provider-injected PORT > local default.
_PORT: int = int(os.getenv("CORALSENSE_PORT") or os.getenv("PORT") or "8000")
_LOG_LEVEL: str = os.getenv("CORALSENSE_LOG_LEVEL", "info").lower()
_MAX_BATCH_SIZE: int = int(os.getenv("CORALSENSE_MAX_BATCH", "50"))

# CORS: set CORALSENSE_CORS_ORIGINS to a comma-separated list to enable.
# Wildcard credentialed CORS is never enabled.
_CORS_ORIGINS: list[str] = [
    o.strip() for o in os.getenv("CORALSENSE_CORS_ORIGINS", "").split(",") if o.strip()
]

_API_VERSION = "0.1.0"
_PROJECT_TITLE = (
    "Oceanographic: A Machine Learning-Driven Sonar Framework "
    "for Real-Time Coral Reef Habitat Prediction and Marine Ecosystem Monitoring"
)

# ---------------------------------------------------------------------------
# Lifespan — model loading on startup
# ---------------------------------------------------------------------------


@asynccontextmanager
async def lifespan(app: FastAPI):  # type: ignore[type-arg]
    """Load champion models at startup; gracefully degrades if unavailable."""
    loader = ModelLoader()
    try:
        from src.config import get_config

        loader.load(cfg=get_config())
    except Exception as exc:
        logger.error("Startup model loading failed: %s", exc)
    app.state.loader = loader
    yield
    # Shutdown: nothing to release (models are in-process objects).


# ---------------------------------------------------------------------------
# Application
# ---------------------------------------------------------------------------

app = FastAPI(
    title=_PROJECT_TITLE,
    version=_API_VERSION,
    description=(
        "Sonar-based coral reef habitat condition and restoration suitability "
        "classification service.\n\n"
        "**Scientific disclosure.** All predictions come from models trained on a "
        "*synthetic prototype dataset* whose labels are *algorithmically generated* "
        "from variables that are also supplied to the models as predictors "
        "(label-construction leakage / circular supervision). Published metrics "
        "measure recovery of the synthetic generation rules and MLOps pipeline "
        "behaviour, **not validated real-world coral-reef prediction accuracy**. "
        "No independent biological ground truth and no external validation exist. "
        "**Do not use for real conservation decisions.**"
    ),
    lifespan=lifespan,
    docs_url="/docs",
    openapi_url="/openapi.json",
)

if _CORS_ORIGINS:
    app.add_middleware(
        CORSMiddleware,
        allow_origins=_CORS_ORIGINS,
        allow_credentials=False,  # never allow credentialed wildcard CORS
        allow_methods=["GET", "POST"],
        allow_headers=["Content-Type"],
    )

# ---------------------------------------------------------------------------
# Dependency — model loader
# ---------------------------------------------------------------------------


def get_loader(request: Request) -> ModelLoader:
    """
    FastAPI dependency that returns the application-scoped ModelLoader.

    Raise 503 if the loader has not been initialised (guards against startup-
    order edge cases).  Tests replace this dependency via
    ``app.dependency_overrides[get_loader]``.
    """
    loader: ModelLoader | None = getattr(request.app.state, "loader", None)
    if loader is None:
        raise HTTPException(status_code=503, detail="Service is starting up; please retry.")
    return loader


# Annotated type alias used in all endpoint signatures to avoid B008.
LoaderDep = Annotated[ModelLoader, Depends(get_loader)]

# ---------------------------------------------------------------------------
# Helper
# ---------------------------------------------------------------------------


def _require_ready(loader: ModelLoader, task: str = "both") -> None:
    """Raise 503 if the required model(s) are not loaded."""
    if task in ("health", "both") and not loader.health_ready:
        raise HTTPException(
            status_code=503,
            detail="Reef-health champion model is not available. Check server logs.",
        )
    if task in ("restoration", "both") and not loader.restoration_ready:
        raise HTTPException(
            status_code=503,
            detail="Restoration-suitability champion model is not available. Check server logs.",
        )


def _now_iso() -> str:
    return datetime.now(UTC).isoformat()


# ---------------------------------------------------------------------------
# Endpoints
# ---------------------------------------------------------------------------


@app.get("/", response_model=RootResponse, tags=["Info"])
def root() -> dict[str, Any]:
    """Project index with documentation links and synthetic-data disclaimer."""
    return {
        "project": _PROJECT_TITLE,
        "api_version": _API_VERSION,
        "docs_url": "/docs",
        "openapi_url": "/openapi.json",
        "endpoints": [
            "GET  /",
            "GET  /health",
            "GET  /ready",
            "GET  /model-info",
            "POST /predict/reef-health",
            "POST /predict/restoration",
            "POST /predict/both",
            "POST /predict/batch",
        ],
        "synthetic_data_disclaimer": _DISCLAIMER,
    }


@app.get("/health", response_model=ServiceHealthResponse, tags=["Info"])
def service_health(loader: LoaderDep) -> dict[str, Any]:
    """
    Process **liveness** probe.

    Always returns 200 while the process is serving, reporting ``degraded``
    when a champion model is missing, so that a container orchestrator does
    not restart a running-but-degraded instance.  Use ``GET /ready`` to gate
    traffic on inference actually being available.
    """
    return {
        "status": "ok" if loader.is_ready else "degraded",
        "health_model_ready": loader.health_ready,
        "restoration_model_ready": loader.restoration_ready,
        "timestamp": _now_iso(),
    }


@app.get(
    "/ready",
    response_model=ReadinessResponse,
    tags=["Info"],
    responses={503: {"model": ReadinessResponse, "description": "One or both models unavailable"}},
)
def service_ready(loader: LoaderDep, response: Response) -> dict[str, Any]:
    """
    Deployment **readiness** probe.

    Returns 200 only when both champion pipelines are loaded, and 503 when
    either is unavailable, so a hosting provider routes traffic only to
    instances that can actually serve predictions.  The body is identical in
    both cases and contains no path, URI, configuration value, or traceback.
    """
    ready = loader.is_ready
    if not ready:
        response.status_code = 503
    return {
        "ready": ready,
        "health_model_ready": loader.health_ready,
        "restoration_model_ready": loader.restoration_ready,
        "timestamp": _now_iso(),
    }


@app.get("/model-info", response_model=ModelInfoResponse, tags=["Info"])
def model_info(loader: LoaderDep) -> dict[str, Any]:
    """
    Safe champion-model metadata for both tasks.

    Never exposes filesystem paths, MLflow URIs, or internal configuration.
    """
    info = loader.model_info()
    return {
        "health": info.get("health", {"available": False}),
        "restoration": info.get("restoration", {"available": False}),
        "synthetic_data_disclaimer": _DISCLAIMER,
    }


@app.post("/predict/reef-health", response_model=PredictionResponse, tags=["Predict"])
def predict_reef_health(obs: ObservationInput, loader: LoaderDep) -> dict[str, Any]:
    """
    Predict reef habitat condition for one observation.

    Returns the predicted class, per-class probabilities, and model metadata.
    """
    _require_ready(loader, task="health")
    try:
        result = loader.get_health().predict_single(obs.model_dump())
    except Exception as exc:
        logger.error("Reef-health prediction error: %s", exc)
        raise HTTPException(
            status_code=500, detail="Prediction failed. Check server logs."
        ) from exc
    return result


@app.post("/predict/restoration", response_model=PredictionResponse, tags=["Predict"])
def predict_restoration(obs: ObservationInput, loader: LoaderDep) -> dict[str, Any]:
    """
    Predict restoration suitability for one observation.

    Returns the predicted class, per-class probabilities, and model metadata.
    """
    _require_ready(loader, task="restoration")
    try:
        result = loader.get_restoration().predict_single(obs.model_dump())
    except Exception as exc:
        logger.error("Restoration prediction error: %s", exc)
        raise HTTPException(
            status_code=500, detail="Prediction failed. Check server logs."
        ) from exc
    return result


@app.post("/predict/both", response_model=BothPredictionResponse, tags=["Predict"])
def predict_both(obs: ObservationInput, loader: LoaderDep) -> dict[str, Any]:
    """
    Predict reef-health and restoration-suitability simultaneously.

    The observation is run through both champion models in one request.
    """
    _require_ready(loader, task="both")
    record = obs.model_dump()
    try:
        health_result = loader.get_health().predict_single(record)
        restoration_result = loader.get_restoration().predict_single(record)
    except Exception as exc:
        logger.error("Combined prediction error: %s", exc)
        raise HTTPException(
            status_code=500, detail="Prediction failed. Check server logs."
        ) from exc
    return {"health": health_result, "restoration": restoration_result}


@app.post("/predict/batch", response_model=BatchPredictionResponse, tags=["Predict"])
def predict_batch(body: BatchRequest, loader: LoaderDep) -> dict[str, Any]:
    """
    Predict reef-health and restoration-suitability for multiple observations.

    Maximum batch size: ``CORALSENSE_MAX_BATCH`` (default 50).
    """
    if len(body.observations) > _MAX_BATCH_SIZE:
        raise HTTPException(
            status_code=422,
            detail=(
                f"Batch too large: {len(body.observations)} observations; "
                f"maximum is {_MAX_BATCH_SIZE}."
            ),
        )
    _require_ready(loader, task="both")

    df = pd.DataFrame([obs.model_dump() for obs in body.observations])
    try:
        health_preds = loader.get_health().predict_batch(df)
        restoration_preds = loader.get_restoration().predict_batch(df)
    except Exception as exc:
        logger.error("Batch prediction error: %s", exc)
        raise HTTPException(
            status_code=500, detail="Batch prediction failed. Check server logs."
        ) from exc

    results = [
        {"health": h, "restoration": r}
        for h, r in zip(health_preds, restoration_preds, strict=True)
    ]
    return {
        "count": len(results),
        "results": results,
        "synthetic_data_disclaimer": _DISCLAIMER,
    }


