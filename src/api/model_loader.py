"""
src/api/model_loader.py — Champion model loading service for the CoralSense API.

Design
------
``ModelLoader`` loads both champion inference pipelines once at application
startup and exposes them for the lifetime of the process.

Model-loading modes
-------------------
The loading mode is controlled by the ``CORALSENSE_MODEL_MODE`` environment
variable:

``registry`` (default)
    Uses ``InferencePipeline`` which queries the live MLflow registry.
    Suitable for local development where ``artifacts/mlruns.db`` is accessible.

``bundle``
    Uses ``BundleInferencePipeline`` which loads from a pre-exported,
    checksum-verified deployment bundle (``deploy/bundles/``).
    Required for Docker containers where MLflow host-absolute paths are
    unavailable.  The bundle path is set by ``CORALSENSE_BUNDLE_PATH``.

Key safety rules enforced here
-------------------------------
- ``fit`` and ``fit_transform`` are NEVER called.
- No model version is registered or promoted.
- Internal paths and MLflow URIs are never included in the public model-info
  output; only safe, presentation-appropriate metadata is exposed.

Dependency injection
--------------------
``get_loader`` is a FastAPI dependency function.  Tests replace it via
``app.dependency_overrides[get_loader]`` to inject a fake loader without
touching the real MLflow database or model files.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path
from typing import Any

from src.config import Config

logger = logging.getLogger(__name__)

_SYNTHETIC_DISCLAIMER = (
    "Predictions generated by a model trained on synthetic data only. "
    "Do not use to guide real-world conservation decisions."
)

_PROJECT_ROOT = Path(__file__).resolve().parents[2]
_DEFAULT_BUNDLE_DIR = _PROJECT_ROOT / "deploy" / "bundles"


def _get_model_mode() -> str:
    """Return the model-loading mode from the environment (default: 'registry')."""
    return os.getenv("CORALSENSE_MODEL_MODE", "registry").lower()


def _get_bundle_dir() -> Path:
    """Return the bundle directory from the environment."""
    return Path(os.getenv("CORALSENSE_BUNDLE_PATH", str(_DEFAULT_BUNDLE_DIR)))


def _load_pipeline(task: str, mode: str, cfg: Config | None, bundle_dir: Path):
    """Create and return an inference pipeline for *task* in the given *mode*."""
    if mode == "bundle":
        from src.api.bundle_loader import BundleInferencePipeline  # noqa: PLC0415

        return BundleInferencePipeline(task=task, bundle_dir=bundle_dir)
    else:
        from src.models.predict import InferencePipeline  # noqa: PLC0415

        return InferencePipeline(task=task, cfg=cfg)


class ModelLoader:
    """
    Singleton-style holder for the two champion inference pipelines.

    ``load()`` must be called once before any prediction endpoint is used.
    If loading fails the loader remains in a ``not is_ready`` state so that
    the API starts and returns 503 rather than crashing.
    """

    def __init__(self) -> None:
        self._health = None
        self._restoration = None

    def load(self, cfg: Config | None = None) -> None:
        """
        Load champion models.  Logs errors but never raises so the app can
        start in a degraded state and return 503 for unavailable models.
        """
        mode = _get_model_mode()
        bundle_dir = _get_bundle_dir()
        logger.info("Loading champion inference pipelines (mode=%s) …", mode)

        try:
            self._health = _load_pipeline("health", mode, cfg, bundle_dir)
            logger.info("Health pipeline loaded: %s", self._health.registered_model_name)
        except Exception as exc:
            logger.error("Health model unavailable: %s", exc)
            self._health = None

        try:
            self._restoration = _load_pipeline("restoration", mode, cfg, bundle_dir)
            logger.info("Restoration pipeline loaded: %s", self._restoration.registered_model_name)
        except Exception as exc:
            logger.error("Restoration model unavailable: %s", exc)
            self._restoration = None

        if self.is_ready:
            logger.info("Both champion models loaded successfully (mode=%s).", mode)
        else:
            logger.warning(
                "One or more champion models failed to load. "
                "Prediction endpoints will return 503 until corrected."
            )

    @property
    def health_ready(self) -> bool:
        return self._health is not None

    @property
    def restoration_ready(self) -> bool:
        return self._restoration is not None

    @property
    def is_ready(self) -> bool:
        return self.health_ready and self.restoration_ready

    def get_health(self):
        """Return the health inference pipeline or raise RuntimeError."""
        if self._health is None:
            raise RuntimeError("Health champion model is not available.")
        return self._health

    def get_restoration(self):
        """Return the restoration inference pipeline or raise RuntimeError."""
        if self._restoration is None:
            raise RuntimeError("Restoration champion model is not available.")
        return self._restoration

    def model_info(self) -> dict[str, Any]:
        """
        Return safe metadata for both champion models.

        Excludes internal filesystem paths, MLflow tracking URIs, and any
        field that reveals server configuration details.
        """
        info: dict[str, Any] = {}
        for task, pipeline in [("health", self._health), ("restoration", self._restoration)]:
            if pipeline is None:
                info[task] = {"available": False}
                continue
            champion = pipeline._champion_info  # type: ignore[union-attr]
            info[task] = {
                "registered_model_name": champion["registered_model_name"],
                "version": champion["version"],
                "alias": champion["alias"],
                "algo_name": champion["algo_name"],
                "label_names": champion["label_names"],
                "run_id": champion["run_id"],
                "cv_macro_f1": champion.get("cv_macro_f1"),
                "task": champion["task"],
                "synthetic_data_disclaimer": _SYNTHETIC_DISCLAIMER,
                "available": True,
            }
        return info
