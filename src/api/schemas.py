"""
src/api/schemas.py — Pydantic request and response schemas for the CoralSense API.

All field bounds mirror the Pandera schema in src/data/validate.py so that
valid API inputs are also valid synthetic-data-schema inputs.

SYNTHETIC-DATA DISCLAIMER
--------------------------
All predictions are generated by a model trained on *synthetic* data.
They must NOT be used to guide real-world coral-reef conservation decisions.
"""

from __future__ import annotations

import math
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

# ---------------------------------------------------------------------------
# Domain constants (kept in sync with src/data/validate.py)
# ---------------------------------------------------------------------------

VALID_REGIONS: tuple[str, ...] = (
    "Lakshadweep",
    "Gulf of Mannar",
    "Gulf of Kutch",
    "Andaman and Nicobar Islands",
)

HEALTH_CLASSES: tuple[str, ...] = (
    "bleached",
    "healthy",
    "severely_degraded",
    "stressed",
)

RESTORATION_CLASSES: tuple[str, ...] = (
    "moderately_suitable",
    "suitable",
    "unsuitable",
)

MAX_BATCH_SIZE: int = 50

_DISCLAIMER = (
    "Predictions generated by a model trained on synthetic data only. "
    "Do not use to guide real-world conservation decisions."
)

# Literal type for the four supported reef regions.
RegionLiteral = Literal[
    "Lakshadweep",
    "Gulf of Mannar",
    "Gulf of Kutch",
    "Andaman and Nicobar Islands",
]

# ---------------------------------------------------------------------------
# Request schemas
# ---------------------------------------------------------------------------


class ObservationInput(BaseModel):
    """
    One raw sonar-and-environmental observation.

    All 16 inference features are required.  Spatial metadata (latitude,
    longitude, timestamp) is optional and not used during inference.
    Target labels (reef_health, restoration_suitability) are never accepted.
    """

    model_config = ConfigDict(extra="forbid")

    # ── Optional spatial metadata (not used for inference) ──────────────────
    timestamp: str | None = Field(
        None,
        description="ISO 8601 UTC observation timestamp (metadata only, not used for inference).",
    )
    latitude: Annotated[float | None, Field(None, ge=-90.0, le=90.0)] = None
    longitude: Annotated[float | None, Field(None, ge=-180.0, le=180.0)] = None

    # ── Required inference features ──────────────────────────────────────────
    region: RegionLiteral = Field(
        ...,
        description="One of the four supported Indian reef regions.",
    )
    depth_m: float = Field(..., ge=0.0, le=50.0, description="Sensor depth (m).")
    water_temperature_c: float = Field(
        ..., ge=10.0, le=42.0, description="In-situ water temperature (°C)."
    )
    ph: float = Field(..., ge=7.0, le=9.0, description="Seawater pH (total scale).")
    salinity_ppt: float = Field(..., ge=20.0, le=50.0, description="Practical salinity (ppt).")
    dissolved_oxygen_mg_l: float = Field(
        ..., ge=0.0, le=15.0, description="Dissolved oxygen (mg/L)."
    )
    turbidity_ntu: float = Field(..., ge=0.0, le=100.0, description="Water turbidity (NTU).")
    light_intensity: float = Field(
        ..., ge=0.0, le=3000.0, description="PAR light intensity (µmol m⁻² s⁻¹)."
    )
    current_speed_m_s: float = Field(
        ..., ge=0.0, le=5.0, description="Near-bottom current speed (m/s)."
    )
    sonar_backscatter: float = Field(
        ..., ge=-60.0, le=0.0, description="Acoustic backscatter (dB); hard reef ≈ −10 to −3 dB."
    )
    rugosity_index: float = Field(
        ..., ge=1.0, le=10.0, description="Benthic rugosity (1 = flat, ≥3.5 = complex reef)."
    )
    hard_substrate_percentage: float = Field(
        ..., ge=0.0, le=100.0, description="Hard substrate coverage (%)."
    )
    acoustic_complexity_index: float = Field(
        ..., ge=0.0, le=1.0, description="Normalised acoustic complexity [0, 1]."
    )
    coral_cover_percentage: float = Field(
        ..., ge=0.0, le=100.0, description="Live coral cover (%)."
    )
    bleaching_percentage: float = Field(
        ..., ge=0.0, le=100.0, description="Bleached coral tissue fraction (%)."
    )
    disease_percentage: float = Field(
        ..., ge=0.0, le=100.0, description="Disease-affected colony fraction (%)."
    )

    @model_validator(mode="after")
    def _require_finite_floats(self) -> ObservationInput:
        """Reject NaN and infinite values in any numeric field."""
        numeric_fields = [
            "latitude",
            "longitude",
            "depth_m",
            "water_temperature_c",
            "ph",
            "salinity_ppt",
            "dissolved_oxygen_mg_l",
            "turbidity_ntu",
            "light_intensity",
            "current_speed_m_s",
            "sonar_backscatter",
            "rugosity_index",
            "hard_substrate_percentage",
            "acoustic_complexity_index",
            "coral_cover_percentage",
            "bleaching_percentage",
            "disease_percentage",
        ]
        for name in numeric_fields:
            val = getattr(self, name)
            if val is not None and (math.isnan(val) or math.isinf(val)):
                raise ValueError(f"'{name}' must be a finite number, got {val!r}")
        return self


class BatchRequest(BaseModel):
    """A bounded collection of observations for batch inference."""

    model_config = ConfigDict(extra="forbid")

    observations: list[ObservationInput] = Field(
        ...,
        min_length=1,
        max_length=MAX_BATCH_SIZE,
        description=f"1–{MAX_BATCH_SIZE} observations.",
    )


# ---------------------------------------------------------------------------
# Response schemas
# ---------------------------------------------------------------------------


class PredictionResponse(BaseModel):
    """Result of a single-task inference call."""

    predicted_class: str
    probabilities: dict[str, float]
    confidence: float
    task: str
    registered_model_name: str
    model_version: str
    model_alias: str
    run_id: str
    prediction_timestamp: str
    synthetic_data_disclaimer: str


class BothPredictionResponse(BaseModel):
    """Combined reef-health and restoration-suitability result."""

    health: PredictionResponse
    restoration: PredictionResponse


class BatchPredictionResponse(BaseModel):
    """Batch inference results."""

    count: int
    results: list[BothPredictionResponse]
    synthetic_data_disclaimer: str


class ModelInfoEntry(BaseModel):
    """Safe metadata for one champion model."""

    registered_model_name: str
    version: str
    alias: str
    algo_name: str
    label_names: list[str]
    run_id: str
    cv_macro_f1: float | None
    task: str
    synthetic_data_disclaimer: str
    available: bool


class ModelInfoResponse(BaseModel):
    """Champion metadata for both tasks."""

    health: ModelInfoEntry | dict[str, Any]
    restoration: ModelInfoEntry | dict[str, Any]
    synthetic_data_disclaimer: str


class ServiceHealthResponse(BaseModel):
    """API liveness and readiness status."""

    status: str
    health_model_ready: bool
    restoration_model_ready: bool
    timestamp: str


class RootResponse(BaseModel):
    """Root endpoint index."""

    project: str
    api_version: str
    docs_url: str
    openapi_url: str
    endpoints: list[str]
    synthetic_data_disclaimer: str
