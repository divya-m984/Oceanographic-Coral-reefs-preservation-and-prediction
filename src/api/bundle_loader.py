"""
src/api/bundle_loader.py — Bundle-mode inference pipeline for containers.

In bundle mode (``CORALSENSE_MODEL_MODE=bundle``) the API loads artefacts
from a pre-exported, checksum-verified deployment bundle instead of querying
the MLflow registry.  This removes the runtime dependency on host-absolute
MLflow artifact paths and makes the inference service fully self-contained
inside a Docker container.

The ``BundleInferencePipeline`` exposes the same interface as
``src.models.predict.InferencePipeline`` so that ``ModelLoader`` works
identically in both modes.

SAFETY GUARANTEES
-----------------
- No fit or fit_transform is ever called.
- No model version is registered or promoted.
- Checksums are re-verified on every load call.
- Startup fails immediately if a checksum mismatch is detected.
- No MLflow client is used; no network call is made.

SYNTHETIC-DATA DISCLAIMER
--------------------------
All predictions are generated by a model trained on synthetic data only.
Results must NOT be used to guide real-world conservation decisions.
"""

from __future__ import annotations

import hashlib
import json
import logging
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd
from sklearn.utils.validation import check_is_fitted

logger = logging.getLogger(__name__)

_PROJECT_ROOT = Path(__file__).resolve().parents[2]
_DEFAULT_BUNDLE_DIR = _PROJECT_ROOT / "deploy" / "bundles"

_SYNTHETIC_DISCLAIMER = (
    "Predictions generated by a model trained on synthetic data only. "
    "Do not use to guide real-world conservation decisions."
)

_VALID_TASKS = ("health", "restoration")


# ---------------------------------------------------------------------------
# Checksum verification
# ---------------------------------------------------------------------------


def _sha256_file(path: Path) -> str:
    """Return SHA-256 hex digest of *path*."""
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _verify_checksum(path: Path, expected: str, label: str) -> None:
    """Raise RuntimeError if the file's SHA-256 does not match *expected*."""
    actual = _sha256_file(path)
    if actual != expected:
        raise RuntimeError(
            f"Bundle checksum mismatch for {label}: "
            f"expected {expected[:16]}… got {actual[:16]}… "
            f"The bundle may be corrupt or was modified after export. "
            f"Re-run: python scripts/export_champions.py"
        )


# ---------------------------------------------------------------------------
# Derived-feature engineering (mirrors src/models/predict._add_derived_features)
# ---------------------------------------------------------------------------


def _add_derived_features(df: pd.DataFrame) -> pd.DataFrame:
    """Add the 6 derived reef features.  Must stay in sync with build_features.py."""
    out = df.copy()
    out["thermal_stress_index"] = ((out["water_temperature_c"] - 28.5) / 4.5).clip(0.0, 1.0)
    out["oxygen_stress_index"] = ((6.0 - out["dissolved_oxygen_mg_l"]) / 3.5).clip(0.0, 1.0)
    out["acidity_deviation"] = (out["ph"] - 8.1).abs()
    tsi = out["thermal_stress_index"]
    osi = out["oxygen_stress_index"]
    ph_stress = (out["acidity_deviation"] / 0.5).clip(0.0, 1.0)
    turb_stress = (out["turbidity_ntu"] / 32.0).clip(0.0, 1.0)
    out["water_quality_index"] = (
        1.0 - (0.40 * tsi + 0.30 * osi + 0.20 * ph_stress + 0.10 * turb_stress)
    ).clip(0.0, 1.0)
    hard = out["hard_substrate_percentage"]
    rug = out["rugosity_index"]
    out["substrate_stability_score"] = (0.60 * (hard / 100.0) + 0.40 * ((rug - 1.0) / 9.0)).clip(
        0.0, 1.0
    )
    out["structural_complexity_score"] = (
        0.50 * out["acoustic_complexity_index"] + 0.50 * ((rug - 1.0) / 9.0)
    ).clip(0.0, 1.0)
    return out


# ---------------------------------------------------------------------------
# BundleInferencePipeline
# ---------------------------------------------------------------------------


class BundleInferencePipeline:
    """
    Bundle-mode inference pipeline.

    Loads artefacts from a deployment bundle produced by
    ``scripts/export_champions.py``.  Compatible interface with
    ``src.models.predict.InferencePipeline``.

    Parameters
    ----------
    task:
        ``"health"`` or ``"restoration"``.
    bundle_dir:
        Root bundle directory.  Defaults to ``deploy/bundles/``.
    """

    def __init__(
        self,
        task: str,
        bundle_dir: Path | None = None,
    ) -> None:
        if task not in _VALID_TASKS:
            raise ValueError(f"task must be one of {_VALID_TASKS}, got '{task}'")
        self.task = task
        self._bundle_dir = bundle_dir or _DEFAULT_BUNDLE_DIR
        self._task_dir = self._bundle_dir / task

        self._metadata: dict[str, Any] = {}
        self._payload: dict[str, Any] = {}
        self._preprocessor: Any = None
        self._champion_info: dict[str, Any] = {}

        self._load()

    # ------------------------------------------------------------------
    # Loading
    # ------------------------------------------------------------------

    def _load(self) -> None:
        """Load and verify bundle artefacts. Raises on any failure."""
        # 1. Metadata
        meta_path = self._task_dir / "metadata.json"
        if not meta_path.exists():
            raise FileNotFoundError(
                f"Bundle metadata not found: {meta_path}. Run: python scripts/export_champions.py"
            )
        with meta_path.open() as fh:
            self._metadata = json.load(fh)

        logger.info(
            "[bundle/%s] Loading v%s (%s) from %s",
            self.task,
            self._metadata.get("version"),
            self._metadata.get("algo_name"),
            self._task_dir,
        )

        # 2. Verify and load payload
        payload_path = self._task_dir / "payload.joblib"
        _verify_checksum(
            payload_path,
            self._metadata["checksum_payload"],
            f"{self.task}/payload.joblib",
        )
        self._payload = joblib.load(payload_path)
        logger.debug("[bundle/%s] payload loaded", self.task)

        # 3. Verify and load preprocessor (never refit)
        preprocessor_path = self._task_dir / "preprocessor.joblib"
        _verify_checksum(
            preprocessor_path,
            self._metadata["checksum_preprocessor"],
            f"{self.task}/preprocessor.joblib",
        )
        self._preprocessor = joblib.load(preprocessor_path)
        check_is_fitted(self._preprocessor)
        logger.debug("[bundle/%s] preprocessor loaded (fitted=True)", self.task)

        # 4. Build champion_info dict (same structure as registry mode)
        self._champion_info = {
            "registered_model_name": self._metadata["registered_model_name"],
            "version": str(self._metadata["version"]),
            "alias": self._metadata["alias"],
            "run_id": self._metadata["run_id"],
            "algo_name": self._metadata["algo_name"],
            "label_names": self._metadata["label_names"],
            "cv_macro_f1": self._metadata["cv_macro_f1"],
            "task": self.task,
        }

        logger.info(
            "[bundle/%s] Ready — model=%s v%s alias=%s",
            self.task,
            self._champion_info["registered_model_name"],
            self._champion_info["version"],
            self._champion_info["alias"],
        )

    # ------------------------------------------------------------------
    # Feature preparation
    # ------------------------------------------------------------------

    def _prepare_features(self, df: pd.DataFrame) -> np.ndarray:
        """Add derived features, reorder to training column order, transform."""
        df_feat = _add_derived_features(df)
        input_cols = list(self._preprocessor.feature_names_in_)
        missing = [c for c in input_cols if c not in df_feat.columns]
        if missing:
            raise ValueError(f"Features missing after engineering: {missing}")
        X = df_feat[input_cols]
        # NEVER call fit or fit_transform — transform only
        return self._preprocessor.transform(X)

    # ------------------------------------------------------------------
    # Public prediction interface (same as InferencePipeline)
    # ------------------------------------------------------------------

    def predict_single(self, record: dict[str, Any]) -> dict[str, Any]:
        """Predict for a single sensor record."""
        return self.predict_batch(pd.DataFrame([record]))[0]

    def predict_batch(self, raw_input: pd.DataFrame | Path | str) -> list[dict[str, Any]]:
        """Predict for multiple sensor records."""
        if isinstance(raw_input, (str, Path)):
            df = pd.read_csv(raw_input)
        else:
            df = raw_input.copy()

        X_t = self._prepare_features(df)
        estimator = self._payload["estimator"]
        label_encoder = self._payload.get("label_encoder")

        if label_encoder is not None:
            y_pred_int = estimator.predict(X_t)
            y_pred = label_encoder.inverse_transform(y_pred_int)
            proba_array = (
                estimator.predict_proba(X_t) if hasattr(estimator, "predict_proba") else None
            )
            proba_classes = [str(c) for c in label_encoder.classes_]
        else:
            y_pred = estimator.predict(X_t)
            proba_array = (
                estimator.predict_proba(X_t) if hasattr(estimator, "predict_proba") else None
            )
            proba_classes = [str(c) for c in estimator.classes_]

        ts = datetime.now(UTC).isoformat()

        results = []
        for i, pred_class in enumerate(y_pred):
            proba_dict: dict[str, float] = {}
            confidence = 1.0
            if proba_array is not None:
                row = proba_array[i]
                proba_dict = {
                    proba_classes[j]: round(float(row[j]), 6) for j in range(len(proba_classes))
                }
                confidence = round(float(row.max()), 6)

            results.append(
                {
                    "predicted_class": str(pred_class),
                    "probabilities": proba_dict,
                    "confidence": confidence,
                    "task": self.task,
                    "registered_model_name": self._champion_info["registered_model_name"],
                    "model_version": self._champion_info["version"],
                    "model_alias": self._champion_info["alias"],
                    "run_id": self._champion_info["run_id"],
                    "prediction_timestamp": ts,
                    "synthetic_data_disclaimer": _SYNTHETIC_DISCLAIMER,
                }
            )
        return results

    # ------------------------------------------------------------------
    # Properties (same as InferencePipeline)
    # ------------------------------------------------------------------

    @property
    def label_names(self) -> list[str]:
        return self._metadata["label_names"]

    @property
    def algo_name(self) -> str:
        return self._metadata["algo_name"]

    @property
    def model_version(self) -> str:
        return str(self._metadata["version"])

    @property
    def registered_model_name(self) -> str:
        return self._metadata["registered_model_name"]
