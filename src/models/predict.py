"""
src/models/predict.py — Production inference pipeline for CoralSense.

Responsibilities
----------------
- Load the champion model version from the MLflow Model Registry.
- Load the fitted preprocessor (never refit; transform only).
- Accept raw sensor records as single dicts, DataFrames, or CSV paths.
- Enforce correct feature ordering and reject missing / unrecognised fields.
- Return structured predictions with class probabilities and confidence score.

SYNTHETIC-DATA DISCLAIMER
--------------------------
All predictions are generated by a model trained on *synthetic* data.
They must NOT be used to guide actual coral reef conservation decisions.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd
from sklearn.utils.validation import check_is_fitted

from src.config import Config, get_config, setup_logging
from src.models.registry import get_champion_version

logger = logging.getLogger(__name__)

_SYNTHETIC_DISCLAIMER = (
    "Predictions generated by a model trained on synthetic data only. "
    "Do not use to guide real-world conservation decisions."
)

_VALID_TASKS = ("health", "restoration")

# Features the preprocessor was fitted on (from build_features.py)
# Categorical features are the last column(s) before engineering.
_REQUIRED_RAW_FEATURES = [
    "depth_m",
    "water_temperature_c",
    "ph",
    "salinity_ppt",
    "dissolved_oxygen_mg_l",
    "turbidity_ntu",
    "light_intensity",
    "current_speed_m_s",
    "sonar_backscatter",
    "rugosity_index",
    "hard_substrate_percentage",
    "acoustic_complexity_index",
    "coral_cover_percentage",
    "bleaching_percentage",
    "disease_percentage",
    "region",
]

# Derived features added by build_features.py (in insertion order)
_DERIVED_FEATURES = [
    "thermal_stress_index",
    "oxygen_stress_index",
    "acidity_deviation",
    "water_quality_index",
    "substrate_stability_score",
    "structural_complexity_score",
]


# ---------------------------------------------------------------------------
# Feature engineering (mirrors build_features.py)
# ---------------------------------------------------------------------------


def _add_derived_features(df: pd.DataFrame) -> pd.DataFrame:
    """Add the 6 derived features, clipping to valid ranges."""
    out = df.copy()
    # 1. Thermal stress index
    out["thermal_stress_index"] = ((out["water_temperature_c"] - 28.5) / 4.5).clip(0.0, 1.0)
    # 2. Oxygen stress index
    out["oxygen_stress_index"] = ((6.0 - out["dissolved_oxygen_mg_l"]) / 3.5).clip(0.0, 1.0)
    # 3. Acidity deviation from optimal pH 8.1
    out["acidity_deviation"] = (out["ph"] - 8.1).abs()
    # 4. Water quality index
    tsi = out["thermal_stress_index"]
    osi = out["oxygen_stress_index"]
    ph_stress = (out["acidity_deviation"] / 0.5).clip(0.0, 1.0)
    turb_stress = (out["turbidity_ntu"] / 32.0).clip(0.0, 1.0)
    out["water_quality_index"] = (
        1.0 - (0.40 * tsi + 0.30 * osi + 0.20 * ph_stress + 0.10 * turb_stress)
    ).clip(0.0, 1.0)
    # 5. Substrate stability score
    hard = out["hard_substrate_percentage"]
    rug = out["rugosity_index"]
    out["substrate_stability_score"] = (0.60 * (hard / 100.0) + 0.40 * ((rug - 1.0) / 9.0)).clip(
        0.0, 1.0
    )
    # 6. Structural complexity score
    aci = out["acoustic_complexity_index"]
    out["structural_complexity_score"] = (0.50 * aci + 0.50 * ((rug - 1.0) / 9.0)).clip(0.0, 1.0)
    return out


# ---------------------------------------------------------------------------
# Input validation
# ---------------------------------------------------------------------------


def _validate_raw_input(df: pd.DataFrame) -> None:
    """
    Verify that all required raw features are present.

    Raises
    ------
    ValueError
        If any required column is missing.
    """
    missing = [col for col in _REQUIRED_RAW_FEATURES if col not in df.columns]
    if missing:
        raise ValueError(
            f"Missing required feature columns: {missing}. "
            f"Required fields: {_REQUIRED_RAW_FEATURES}"
        )


def _to_dataframe(raw_input: dict | pd.DataFrame | Path | str) -> pd.DataFrame:
    """Normalise the input to a DataFrame."""
    if isinstance(raw_input, pd.DataFrame):
        return raw_input.copy()
    if isinstance(raw_input, dict):
        return pd.DataFrame([raw_input])
    path = Path(raw_input)
    if not path.exists():
        raise FileNotFoundError(f"Input file not found: {path}")
    return pd.read_csv(path)


# ---------------------------------------------------------------------------
# Inference pipeline
# ---------------------------------------------------------------------------


class InferencePipeline:
    """
    End-to-end inference pipeline for a single CoralSense task.

    Parameters
    ----------
    task:
        ``"health"`` or ``"restoration"``.
    mlflow_uri:
        MLflow SQLite tracking URI.
    processed_dir:
        Directory containing ``preprocessor_{task}.joblib``.
    models_dir:
        Directory containing ``best_model_{task}.joblib``.
    cfg:
        Config instance.
    """

    def __init__(
        self,
        task: str,
        mlflow_uri: str | None = None,
        processed_dir: Path | None = None,
        models_dir: Path | None = None,
        cfg: Config | None = None,
    ) -> None:
        if task not in _VALID_TASKS:
            raise ValueError(f"task must be one of {_VALID_TASKS}, got '{task}'")
        self.task = task
        self._cfg = cfg or get_config()
        self._mlflow_uri = mlflow_uri or self._cfg.mlflow_tracking_uri
        self._processed_dir = processed_dir or self._cfg.paths.processed_data_dir
        self._models_dir = models_dir or self._cfg.paths.models_dir

        # Loaded lazily
        self._champion_info: dict[str, Any] | None = None
        self._payload: dict[str, Any] | None = None
        self._preprocessor: Any | None = None

        self._load()

    # ------------------------------------------------------------------
    # Loading
    # ------------------------------------------------------------------

    def _load(self) -> None:
        """Load champion metadata, model payload, and preprocessor."""
        # 1. Resolve champion from registry
        self._champion_info = get_champion_version(
            self.task,
            mlflow_uri=self._mlflow_uri,
            cfg=self._cfg,
        )
        logger.info(
            "[%s] Champion: model=%s version=%s algo=%s",
            self.task,
            self._champion_info["registered_model_name"],
            self._champion_info["version"],
            self._champion_info["algo_name"],
        )

        # 2. Load joblib payload (estimator + label_encoder + metadata)
        joblib_path = Path(self._champion_info["joblib_path"])
        if not joblib_path.is_absolute():
            joblib_path = self._models_dir / f"best_model_{self.task}.joblib"
        if not joblib_path.exists():
            # Fallback to canonical path
            joblib_path = self._models_dir / f"best_model_{self.task}.joblib"
        if not joblib_path.exists():
            raise FileNotFoundError(
                f"Model payload not found: {joblib_path}. Run src.models.train to generate it."
            )
        self._payload = joblib.load(joblib_path)
        logger.debug("[%s] Loaded payload from %s", self.task, joblib_path)

        # 3. Load fitted preprocessor — NEVER refit
        preprocessor_path = self._processed_dir / f"preprocessor_{self.task}.joblib"
        if not preprocessor_path.exists():
            raise FileNotFoundError(
                f"Preprocessor not found: {preprocessor_path}. "
                "Run src.data.preprocess to generate it."
            )
        self._preprocessor = joblib.load(preprocessor_path)
        # Verify it is fitted — raises NotFittedError if not
        check_is_fitted(self._preprocessor)
        logger.debug("[%s] Loaded preprocessor from %s", self.task, preprocessor_path)

    # ------------------------------------------------------------------
    # Feature preparation
    # ------------------------------------------------------------------

    def _prepare_features(self, df: pd.DataFrame) -> np.ndarray:
        """
        Add derived features, reorder columns to training order, transform.

        Parameters
        ----------
        df:
            Raw input DataFrame (must contain all required raw features).

        Returns
        -------
        Transformed feature array, shape (n_samples, n_transformed_features).
        """
        _validate_raw_input(df)

        # Add derived features
        df_feat = _add_derived_features(df)

        # Use the preprocessor's own expected input column order (pre-transform).
        # payload["feature_names"] contains post-transform names (num__*, cat__*) and
        # is used only for feature importance; it must NOT be used to select input columns.
        input_cols: list[str] = list(self._preprocessor.feature_names_in_)

        # Verify all columns are present after feature engineering
        missing = [c for c in input_cols if c not in df_feat.columns]
        if missing:
            raise ValueError(
                f"Features missing after engineering: {missing}. "
                f"This indicates a derived-feature computation error."
            )

        # Select and reorder columns to match training order (critical!), then transform.
        # NEVER call fit or fit_transform on the preprocessor.
        X = df_feat[input_cols]
        return self._preprocessor.transform(X)

    # ------------------------------------------------------------------
    # Public prediction interface
    # ------------------------------------------------------------------

    def predict_single(self, record: dict[str, Any]) -> dict[str, Any]:
        """
        Predict for a single sensor record.

        Parameters
        ----------
        record:
            Dict mapping feature name → value.  Must include all required raw
            features.  Extra keys are silently ignored.

        Returns
        -------
        Prediction dict (see module docstring for field list).
        """
        return self.predict_batch(pd.DataFrame([record]))[0]

    def predict_batch(self, raw_input: pd.DataFrame | Path | str) -> list[dict[str, Any]]:
        """
        Predict for multiple sensor records.

        Parameters
        ----------
        raw_input:
            DataFrame, path to a CSV file, or string path.

        Returns
        -------
        List of prediction dicts, one per row.
        """
        df = _to_dataframe(raw_input)
        X_t = self._prepare_features(df)

        estimator = self._payload["estimator"]
        label_encoder = self._payload["label_encoder"]

        # Predict integer classes if XGB (label_encoder present)
        if label_encoder is not None:
            y_pred_int = estimator.predict(X_t)
            y_pred = label_encoder.inverse_transform(y_pred_int)
            proba_array = (
                estimator.predict_proba(X_t) if hasattr(estimator, "predict_proba") else None
            )
            # label_encoder.classes_ gives the class for each column of predict_proba.
            proba_classes: list[str] = [str(c) for c in label_encoder.classes_]
        else:
            y_pred = estimator.predict(X_t)
            proba_array = (
                estimator.predict_proba(X_t) if hasattr(estimator, "predict_proba") else None
            )
            # estimator.classes_ gives the class for each column of predict_proba.
            # This may differ in ordering from payload["label_names"].
            proba_classes = [str(c) for c in estimator.classes_]

        ts = datetime.now(UTC).isoformat()
        champion_info = self._champion_info

        results = []
        for i, pred_class in enumerate(y_pred):
            proba_dict: dict[str, float] = {}
            confidence: float = 1.0
            if proba_array is not None:
                row = proba_array[i]
                proba_dict = {
                    proba_classes[j]: round(float(row[j]), 6) for j in range(len(proba_classes))
                }
                confidence = round(float(row.max()), 6)

            results.append(
                {
                    "predicted_class": str(pred_class),
                    "probabilities": proba_dict,
                    "confidence": confidence,
                    "task": self.task,
                    "registered_model_name": champion_info["registered_model_name"],
                    "model_version": champion_info["version"],
                    "model_alias": champion_info["alias"],
                    "run_id": champion_info["run_id"],
                    "prediction_timestamp": ts,
                    "synthetic_data_disclaimer": _SYNTHETIC_DISCLAIMER,
                }
            )

        return results

    # ------------------------------------------------------------------
    # Properties
    # ------------------------------------------------------------------

    @property
    def label_names(self) -> list[str]:
        return self._payload["label_names"]

    @property
    def algo_name(self) -> str:
        return self._payload["algo_name"]

    @property
    def model_version(self) -> str:
        return self._champion_info["version"]

    @property
    def registered_model_name(self) -> str:
        return self._champion_info["registered_model_name"]


# ---------------------------------------------------------------------------
# Convenience functions
# ---------------------------------------------------------------------------


def predict_from_json(
    json_path: Path,
    task: str,
    mlflow_uri: str | None = None,
    processed_dir: Path | None = None,
    models_dir: Path | None = None,
    cfg: Config | None = None,
) -> list[dict[str, Any]]:
    """Load a JSON file and run prediction."""
    with open(json_path, encoding="utf-8") as fh:
        data = json.load(fh)
    if isinstance(data, dict):
        data = [data]
    df = pd.DataFrame(data)
    pipeline = InferencePipeline(
        task,
        mlflow_uri=mlflow_uri,
        processed_dir=processed_dir,
        models_dir=models_dir,
        cfg=cfg,
    )
    return pipeline.predict_batch(df)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    """
    CLI for CoralSense inference.

    Exit codes
    ----------
    0   Success.
    1   Prediction or load error.
    2   Invalid arguments.
    """
    setup_logging(__name__)
    parser = argparse.ArgumentParser(
        description="Run CoralSense predictions using the champion registered model.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--task",
        choices=["health", "restoration"],
        required=True,
        help="Which classifier to use.",
    )
    parser.add_argument(
        "--input",
        required=True,
        help="Path to input JSON (single record or list) or CSV file.",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Optional path to write predictions CSV.",
    )
    parser.add_argument(
        "--mlflow-uri",
        default=None,
        help="MLflow tracking URI (default: from config/env).",
    )
    parser.add_argument(
        "--processed-dir",
        default=None,
        type=Path,
        help="Directory containing fitted preprocessor.",
    )
    parser.add_argument(
        "--models-dir",
        default=None,
        type=Path,
        help="Directory containing best_model joblib file.",
    )
    args = parser.parse_args(argv)

    input_path = Path(args.input)
    if not input_path.exists():
        logger.error("Input file not found: %s", input_path)
        return 2

    try:
        cfg = get_config()
        pipeline = InferencePipeline(
            task=args.task,
            mlflow_uri=args.mlflow_uri,
            processed_dir=args.processed_dir,
            models_dir=args.models_dir,
            cfg=cfg,
        )

        suffix = input_path.suffix.lower()
        if suffix == ".json":
            results = predict_from_json(
                input_path,
                args.task,
                mlflow_uri=args.mlflow_uri,
                processed_dir=args.processed_dir,
                models_dir=args.models_dir,
                cfg=cfg,
            )
        else:
            results = pipeline.predict_batch(input_path)

        # Output
        out_df = pd.DataFrame(results)
        if args.output:
            out_df.to_csv(args.output, index=False)
            logger.info("Predictions written to %s", args.output)
        else:
            print(out_df.to_string(index=False))

        return 0

    except Exception as exc:
        logger.error("Prediction failed: %s", exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
