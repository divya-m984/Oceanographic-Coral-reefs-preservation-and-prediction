"""
src/monitoring/generate_production.py — Synthetic production window generator.

Generates a plausible production dataset by applying configurable distribution
shifts to a subsample of raw observations.  The shifted data simulates a
bleaching/degradation event so that the drift-monitoring pipeline has a
realistic signal to detect.

SYNTHETIC-DATA DISCLAIMER
--------------------------
The produced window is SYNTHETIC.  It does NOT represent real ocean observations.
No accuracy or F1 metrics should be reported for the shifted window because labels
are not recomputed after shifting.
"""

from __future__ import annotations

import logging
from pathlib import Path

import numpy as np
import pandas as pd

from src.config import Config, get_config

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Column-level shift magnitudes (at shift_scale=1.0)
# ---------------------------------------------------------------------------

_SHIFTS: dict[str, float] = {
    "water_temperature_c": +3.0,  # simulated thermal bleaching event
    "bleaching_percentage": +20.0,  # ecological degradation
    "coral_cover_percentage": -15.0,  # coral loss
    "turbidity_ntu": +5.0,  # reduced water clarity
}

# Clipping bounds to keep values physically plausible
_CLIP_BOUNDS: dict[str, tuple[float, float]] = {
    "water_temperature_c": (20.0, 35.0),
    "bleaching_percentage": (0.0, 100.0),
    "coral_cover_percentage": (0.0, 100.0),
    "turbidity_ntu": (0.0, 50.0),
}

_SYNTHETIC_DISCLAIMER = (
    "This production window is SYNTHETIC. It was generated by applying "
    "configurable distribution shifts to raw synthetic observations. "
    "It does NOT represent real ocean data. Labels are NOT recomputed "
    "after shifting and must NOT be used for accuracy assessment."
)


def apply_shift(df: pd.DataFrame, shift_scale: float = 1.0) -> pd.DataFrame:
    """
    Apply distribution shifts to *df* and return a new DataFrame.

    When ``shift_scale=0`` the output is a copy of the input (no drift).
    When ``shift_scale=1`` the standard shifts in ``_SHIFTS`` are applied.
    Intermediate values interpolate linearly.

    The shift is applied to *all* rows; labels (``reef_health``,
    ``restoration_suitability``) are intentionally left unchanged because
    they were generated from the original (unshifted) feature values.

    Parameters
    ----------
    df:
        Input DataFrame (should contain the columns listed in ``_SHIFTS``).
    shift_scale:
        Magnitude multiplier.  Must be >= 0.

    Returns
    -------
    A new DataFrame with shifted numeric columns; all other columns are
    copied unchanged.

    Raises
    ------
    ValueError
        If ``shift_scale`` is negative.
    """
    if shift_scale < 0:
        raise ValueError(f"shift_scale must be >= 0, got {shift_scale}")
    if shift_scale == 0.0:
        return df.copy()

    out = df.copy()
    for col, magnitude in _SHIFTS.items():
        if col not in out.columns:
            logger.debug("Column '%s' not in DataFrame — skipping shift", col)
            continue
        out[col] = out[col] + shift_scale * magnitude
        if col in _CLIP_BOUNDS:
            lo, hi = _CLIP_BOUNDS[col]
            out[col] = out[col].clip(lo, hi)

    return out


def generate_production_window(
    raw_csv: Path,
    production_n: int,
    shift_scale: float,
    rng: np.random.Generator,
    drop_labels: bool = True,
) -> pd.DataFrame:
    """
    Sample *production_n* rows from *raw_csv* and apply distribution shifts.

    Parameters
    ----------
    raw_csv:
        Path to the raw observations CSV.
    production_n:
        Number of rows in the production window.
    shift_scale:
        Drift magnitude (0 = no shift).
    rng:
        NumPy random generator (for reproducible sampling).
    drop_labels:
        If True (default), the target columns ``reef_health`` and
        ``restoration_suitability`` are removed from the output to enforce
        that the production window is treated as unlabeled.

    Returns
    -------
    DataFrame with ``production_n`` rows and optionally dropped label columns.
    """
    df_raw = pd.read_csv(raw_csv)
    n = min(production_n, len(df_raw))
    idx = rng.choice(len(df_raw), size=n, replace=False)
    sampled = df_raw.iloc[idx].reset_index(drop=True)
    shifted = apply_shift(sampled, shift_scale=shift_scale)
    if drop_labels:
        label_cols = [c for c in ("reef_health", "restoration_suitability") if c in shifted.columns]
        shifted = shifted.drop(columns=label_cols)
    return shifted


def generate_reference_window(
    raw_csv: Path,
    reference_n: int,
    rng: np.random.Generator,
) -> pd.DataFrame:
    """
    Sample *reference_n* rows from *raw_csv* without any shift.

    Only inference features are returned (no target columns).

    Parameters
    ----------
    raw_csv:
        Path to the raw observations CSV.
    reference_n:
        Number of rows in the reference window.
    rng:
        NumPy random generator.

    Returns
    -------
    DataFrame with feature columns only.
    """
    df_raw = pd.read_csv(raw_csv)
    n = min(reference_n, len(df_raw))
    idx = rng.choice(len(df_raw), size=n, replace=False)
    sampled = df_raw.iloc[idx].reset_index(drop=True)
    label_cols = [c for c in ("reef_health", "restoration_suitability") if c in sampled.columns]
    return sampled.drop(columns=label_cols)


def save_windows(
    raw_csv: Path | None = None,
    cfg: Config | None = None,
    shift_scale: float | None = None,
    reference_n: int | None = None,
    production_n: int | None = None,
) -> tuple[Path, Path]:
    """
    Generate and persist both the reference and production windows.

    Parameters
    ----------
    raw_csv:
        Path to raw observations.  Defaults to ``cfg.paths.raw_data_dir / raw_filename``.
    cfg:
        Config instance.  Created from defaults if not provided.
    shift_scale:
        Overrides ``monitoring.shift_scale`` from params.
    reference_n:
        Overrides ``monitoring.reference_n`` from params.
    production_n:
        Overrides ``monitoring.production_n`` from params.

    Returns
    -------
    Tuple ``(reference_path, production_path)``.
    """
    cfg = cfg or get_config()
    p = cfg.monitoring

    _shift_scale = shift_scale if shift_scale is not None else p["shift_scale"]
    _reference_n = reference_n if reference_n is not None else p["reference_n"]
    _production_n = production_n if production_n is not None else p["production_n"]

    if raw_csv is None:
        raw_csv = cfg.paths.raw_data_dir / cfg.raw_filename

    rng = np.random.default_rng(cfg.random_seed)

    ref_df = generate_reference_window(raw_csv, _reference_n, rng)
    prod_df = generate_production_window(raw_csv, _production_n, _shift_scale, rng)

    ref_dir = cfg.paths.reference_data_dir
    prod_dir = cfg.paths.production_data_dir
    ref_dir.mkdir(parents=True, exist_ok=True)
    prod_dir.mkdir(parents=True, exist_ok=True)

    ref_path = ref_dir / p["reference_filename"]
    prod_path = prod_dir / p["production_filename"]

    ref_df.to_csv(ref_path, index=False)
    prod_df.to_csv(prod_path, index=False)

    logger.info(
        "Reference window (%d rows) → %s", len(ref_df), ref_path.relative_to(cfg.paths.project_root)
    )
    logger.info(
        "Production window (%d rows, shift_scale=%.2f) → %s",
        len(prod_df),
        _shift_scale,
        prod_path.relative_to(cfg.paths.project_root),
    )
    return ref_path, prod_path
