"""
scripts/export_champions.py — Export champion models to a portable deployment bundle.

The bundle is a directory tree containing self-contained, checksum-verified
snapshots of the champion inference artefacts.  It is designed for use in
Docker containers where the MLflow registry and its host-absolute paths are
not available.

Bundle layout
-------------
    deploy/bundles/
    ├── health/
    │   ├── payload.joblib        (copy of models/best_model_health.joblib)
    │   ├── preprocessor.joblib   (copy of data/processed/preprocessor_health.joblib)
    │   └── metadata.json
    └── restoration/
        ├── payload.joblib        (copy of models/best_model_restoration.joblib)
        ├── preprocessor.joblib   (copy of data/processed/preprocessor_restoration.joblib)
        └── metadata.json

metadata.json fields
--------------------
    task, registered_model_name, version, alias, run_id, algo_name,
    label_names, cv_macro_f1, checksum_payload, checksum_preprocessor,
    exported_at, coralsense_version, synthetic_data_disclaimer

Safety guarantees
-----------------
- Champions are resolved from the live canonical registry at export time.
- No model is trained, registered or promoted.
- No fit or fit_transform is called on any object.
- The canonical database (artifacts/mlruns.db) is never modified.
- Checksums are SHA-256 over the exact bytes that will be deployed.

Usage
-----
    python scripts/export_champions.py
    python scripts/export_champions.py --bundle-dir path/to/custom/dir
    python scripts/export_champions.py --mlflow-uri sqlite:///artifacts/mlruns.db

Exit codes
----------
0   All champions exported and verified.
1   Export failed (model unavailable, checksum error, etc.).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import logging
import shutil
import sys
from datetime import UTC, datetime
from pathlib import Path

from src.config import get_config, setup_logging
from src.models.registry import get_champion_version

logger = logging.getLogger(__name__)

_PROJECT_ROOT = Path(__file__).resolve().parent.parent
_DEFAULT_BUNDLE_DIR = _PROJECT_ROOT / "deploy" / "bundles"

_SYNTHETIC_DISCLAIMER = (
    "Predictions generated by a model trained on synthetic data only. "
    "Do not use to guide real-world conservation decisions."
)


# ---------------------------------------------------------------------------
# Checksum helpers
# ---------------------------------------------------------------------------


def sha256_file(path: Path) -> str:
    """Return the SHA-256 hex digest of the file at *path*."""
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


# ---------------------------------------------------------------------------
# Export logic
# ---------------------------------------------------------------------------


def export_task(
    task: str,
    bundle_dir: Path,
    cfg,
    mlflow_uri: str | None,
) -> Path:
    """
    Export the champion for *task* to *bundle_dir/task/*.

    Returns the path to the written metadata.json.

    Raises
    ------
    FileNotFoundError
        If the source payload or preprocessor file is missing.
    RuntimeError
        If checksum verification fails after copying.
    """
    logger.info("[%s] Resolving champion from registry …", task)
    champion = get_champion_version(task, mlflow_uri=mlflow_uri, cfg=cfg)

    logger.info(
        "[%s] Champion: model=%s version=%s algo=%s run_id=%s",
        task,
        champion["registered_model_name"],
        champion["version"],
        champion["algo_name"],
        champion["run_id"][:8],
    )

    # Source paths — resolved from config (not from the registry's stored joblib_path
    # which may contain the host-absolute path).  We always copy from the canonical
    # local locations that the DVC pipeline produces.
    src_payload = cfg.paths.models_dir / f"best_model_{task}.joblib"
    src_preprocessor = cfg.paths.processed_data_dir / f"preprocessor_{task}.joblib"

    for src in (src_payload, src_preprocessor):
        if not src.exists():
            raise FileNotFoundError(
                f"Source artefact not found: {src}. Run the DVC pipeline first: dvc repro"
            )

    # Compute checksums of originals before copying
    checksum_payload = sha256_file(src_payload)
    checksum_preprocessor = sha256_file(src_preprocessor)
    logger.info("[%s] payload checksum     : %s", task, checksum_payload[:16] + "…")
    logger.info("[%s] preprocessor checksum: %s", task, checksum_preprocessor[:16] + "…")

    # Create bundle task directory
    task_dir = bundle_dir / task
    task_dir.mkdir(parents=True, exist_ok=True)

    # Copy artefacts
    dst_payload = task_dir / "payload.joblib"
    dst_preprocessor = task_dir / "preprocessor.joblib"
    shutil.copy2(src_payload, dst_payload)
    shutil.copy2(src_preprocessor, dst_preprocessor)

    # Verify post-copy checksums
    if sha256_file(dst_payload) != checksum_payload:
        raise RuntimeError(f"[{task}] Payload checksum mismatch after copy — aborting.")
    if sha256_file(dst_preprocessor) != checksum_preprocessor:
        raise RuntimeError(f"[{task}] Preprocessor checksum mismatch after copy — aborting.")
    logger.info("[%s] Post-copy checksums verified.", task)

    # Build metadata
    metadata = {
        "task": task,
        "registered_model_name": champion["registered_model_name"],
        "version": champion["version"],
        "alias": champion["alias"],
        "run_id": champion["run_id"],
        "algo_name": champion["algo_name"],
        "label_names": champion["label_names"],
        "cv_macro_f1": champion["cv_macro_f1"],
        "checksum_payload": checksum_payload,
        "checksum_preprocessor": checksum_preprocessor,
        "exported_at": datetime.now(UTC).isoformat(),
        "coralsense_version": cfg.version,
        "synthetic_data_disclaimer": _SYNTHETIC_DISCLAIMER,
    }

    metadata_path = task_dir / "metadata.json"
    with metadata_path.open("w") as fh:
        json.dump(metadata, fh, indent=2)

    try:
        display_task_dir = task_dir.relative_to(_PROJECT_ROOT)
    except ValueError:
        display_task_dir = task_dir
    logger.info("[%s] Bundle written to %s", task, display_task_dir)
    return metadata_path


def export_all(
    bundle_dir: Path | None = None,
    mlflow_uri: str | None = None,
    cfg=None,
) -> dict[str, Path]:
    """
    Export champions for all tasks and return a dict of ``task → metadata_path``.

    Parameters
    ----------
    bundle_dir:
        Root directory for the bundle.  Defaults to ``deploy/bundles/``.
    mlflow_uri:
        MLflow tracking URI.  Defaults to the project config.
    cfg:
        Config instance.  Created from defaults if None.
    """
    cfg = cfg or get_config()
    bundle_dir = bundle_dir or _DEFAULT_BUNDLE_DIR

    try:
        display_path = bundle_dir.relative_to(_PROJECT_ROOT)
    except ValueError:
        display_path = bundle_dir
    logger.info("Exporting deployment bundle to %s …", display_path)

    results: dict[str, Path] = {}
    for task in ("health", "restoration"):
        results[task] = export_task(task, bundle_dir, cfg, mlflow_uri)

    # Write a top-level bundle manifest
    manifest = {
        "exported_at": datetime.now(UTC).isoformat(),
        "tasks": list(results.keys()),
        "coralsense_version": cfg.version,
        "note": (
            "This bundle is a read-only deployment artefact. "
            "Do not register, promote or retrain from this directory."
        ),
    }
    manifest_path = bundle_dir / "manifest.json"
    with manifest_path.open("w") as fh:
        json.dump(manifest, fh, indent=2)
    try:
        display_manifest = manifest_path.relative_to(_PROJECT_ROOT)
    except ValueError:
        display_manifest = manifest_path
    logger.info("Bundle manifest written to %s", display_manifest)

    return results


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    setup_logging(__name__)
    parser = argparse.ArgumentParser(
        description="Export CoralSense champion models to a portable deployment bundle.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--bundle-dir",
        type=Path,
        default=_DEFAULT_BUNDLE_DIR,
        help="Output directory for the bundle.",
    )
    parser.add_argument(
        "--mlflow-uri",
        default=None,
        help="MLflow tracking URI (default: from config/env).",
    )
    args = parser.parse_args(argv)

    try:
        results = export_all(bundle_dir=args.bundle_dir, mlflow_uri=args.mlflow_uri)
        print(f"\nDeployment bundle exported ({len(results)} tasks):")
        for task, meta_path in results.items():
            print(f"  {task}: {meta_path}")
        print(
            "\nNext steps:\n"
            "  1. Verify: python scripts/verify_deployment_bundle.py\n"
            "  2. Build:  docker compose build\n"
            "  3. Start:  docker compose up -d\n"
        )
        return 0
    except FileNotFoundError as exc:
        logger.error("Missing artefact: %s", exc)
        return 1
    except Exception as exc:  # noqa: BLE001
        logger.error("Export failed: %s", exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
